'use strict';
const path = require('node:path');
const {test, expect} = require('./fixtures.cjs');
const {saveFixture} = require('../helpers/save-fixture.cjs');
const {loadRaw, selectCharacter, previewBase, download, noOverflow} = require('./actions.cjs');

for (const width of [1280, 390]) {
  test(`HTTP ${width}px: full-size base aptitude preview, restore, download and reload`, async ({page, site}) => {
    await page.setViewportSize({width, height: 844});
    const f = saveFixture({size: 2501, characters: 2500, exclusions: true});
    await page.goto(site.url);
    await loadRaw(page, site, f.raw);
    await page.locator('[data-tab="characters"]').click();
    expect(await page.locator('#characterSelect option').count()).toBe(50);
    await expect(page.locator('#baseAptitudeStatus')).toContainText('範本');
    await expect(page.locator('#baseAptitudePreviewBtn')).toBeDisabled();
    await selectCharacter(page, 2);
    await expect(page.locator('#baseAptitudePreviewBtn')).toBeDisabled();
    await expect(page.locator('#baseAptitudeStatus')).toContainText('監');
    await selectCharacter(page, 2500);
    await expect(page.locator('#characterSelect option')).toHaveCount(1);
    await previewBase(page, [21, 21, 57]);
    await expect(page.locator('#baseAptitudeApplyBtn')).toBeDisabled();
    await expect(page.locator('#pendingCount')).toHaveText('0');
    await previewBase(page, [40, 30, 30]);
    await expect(page.locator('#baseAptitudeApplyBtn')).toBeEnabled();
    await page.locator('#baseAptitude1').fill('35');
    await expect(page.locator('#baseAptitudeApplyBtn')).toBeDisabled();
    await expect(page.locator('#baseAptitudePreview')).toContainText('重新預覽');
    await page.locator('#baseAptitudePreviewBtn').click();
    await expect(page.locator('#baseAptitudePreview tbody tr')).toHaveCount(3);
    await noOverflow(page);
    if (process.env.BANDIT_BROWSER_VISUAL) await page.screenshot({path: path.join(process.env.BANDIT_BROWSER_ARTIFACTS, `aptitudes-${width}.png`), fullPage: true});
    await page.locator('#baseAptitudeApplyBtn').click();
    await expect(page.locator('#pendingCount')).toHaveText('2');
    await page.locator('#reviewBtn').click();
    await page.locator('[data-restore="2500,10,2"]').click();
    await expect(page.locator('#pendingCount')).toHaveText('0');
    await page.locator('[data-close="reviewDialog"]').click();
    await page.locator('#undoBtn').click();
    await expect(page.locator('#pendingCount')).toHaveText('2');
    const output = await download(page, site, f.expected([[2500, 10, 2, 40], [2500, 11, 2, 35]]));
    await page.locator('#fileInput').setInputFiles(output);
    await expect(page.locator('#fileName')).toHaveText(path.basename(output));
    await expect(page.locator('#pendingCount')).toHaveText('0');
    await selectCharacter(page, 2500);
    await expect(page.locator('#baseAptitude0')).toHaveValue('40');
    await expect(page.locator('#baseAptitude1')).toHaveValue('35');
    await noOverflow(page);
  });

  test(`HTTP ${width}px: batch cross-page selection, pagination, atomic undo and download`, async ({page, site}) => {
    await page.setViewportSize({width, height: 844});
    const f = saveFixture({size: 2501, characters: 2500});
    await page.goto(site.url); await loadRaw(page, site, f.raw);
    await page.locator('[data-tab="batch"]').click();
    await expect(page.locator('[data-batch-character]')).toHaveCount(50);
    await page.locator('#batchSelectPage').click();
    await page.locator('#batchCharacterNext').click();
    await page.locator('[data-batch-character="51"]').check();
    await expect(page.locator('#batchCharacterCount')).toContainText('已勾選 51');
    await page.locator('#batchAmount').fill('1');
    await page.locator('#batchPreview').click();
    await expect(page.locator('#batchApply')).toBeEnabled();
    await expect(page.locator('#batchRows tr')).toHaveCount(50);
    await page.locator('#batchNext').click();
    await expect(page.locator('#batchRows tr')).toHaveCount(1);
    await page.locator('#batchApply').click();
    await expect(page.locator('#pendingCount')).toHaveText('51');
    await page.locator('#reviewBtn').click();
    await expect(page.locator('#reviewRows tr')).toHaveCount(50);
    await page.locator('#reviewNext').click();
    await expect(page.locator('#reviewRows tr')).toHaveCount(1);
    const expected = f.expected(Array.from({length: 51}, (_, i) => [i + 1, 4, 2, 1]));
    const output = await download(page, site, expected, '#reviewDownloadBtn');
    await page.locator('[data-close="reviewDialog"]').click();
    await page.locator('#undoBtn').click();
    await expect(page.locator('#pendingCount')).toHaveText('0');
    await page.locator('#fileInput').setInputFiles(output);
    await expect(page.locator('#fileName')).toHaveText(path.basename(output));
    await page.locator('[data-tab="batch"]').click();
    await page.locator('#batchKind').selectOption('skillExperience');
    await expect(page.locator('#batchCharacter option')).toHaveCount(50);
    await page.locator('#batchCharacterSearch').fill('#2500');
    await expect(page.locator('#batchCharacter option')).toHaveCount(1);
    await noOverflow(page);
  });
}
